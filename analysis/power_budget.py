#!/usr/bin/env python3
"""Arithmetic worksheet only. No hardware ratings or safety validation.

Run from the project root: python3 analysis/power_budget.py
All efficiencies and auxiliary consumption are illustrative assumptions.
Grid power is an assumed positive reservation, not a verified rail capability.
"""
from decimal import Decimal as D


CEILING = D("120")
ETA = {"heater": D("0.85"), "anode": D("0.80"),
       "screen": D("0.75"), "grid": D("0.70")}
FRONT_END_ETA = D("0.90")
AUX_BUS_W = D("12")

# DC examples; for AC, use real power and separately check RMS/peak current.
SCENARIOS = [
    ("All individual caps", ("7.5", "8"), ("600", ".15"), ("300", ".05"), "1"),
    ("Heater-heavy boundary", ("7.5", "8"), ("300", ".15"), ("280", ".05"), "1"),
    ("Anode-heavy boundary", ("12", "2"), ("600", ".15"), ("500", ".01"), "1"),
    ("Both maximum voltages", ("6.3", ".3"), ("600", ".15"), ("500", ".03"), "1"),
    ("Illustrative 7.5 W grid reservation", ("12", "2"), ("500", ".15"), ("300", ".04"), "7.5"),
    ("First-path upper bound", ("6.3", ".3"), ("100", ".005"), ("0", "0"), "1"),
]


def power(pair):
    return D(pair[0]) * D(pair[1])


def assess(h, a, s, grid):
    watts = dict(zip(ETA, [power(h), power(a), power(s), D(grid)]))
    checks = [
        D("0") <= D(h[0]) <= 50, D("0") <= D(h[1]) <= 8, watts["heater"] <= 60,
        D("0") <= D(a[0]) <= 600, D("0") <= D(a[1]) <= D(".2"), watts["anode"] <= 90,
        D("0") <= D(s[0]) <= 500, D("0") <= D(s[1]) <= D(".05"), watts["screen"] <= 15,
        watts["grid"] >= 0,
    ]
    total = sum(watts.values())
    dc_bus = sum(watts[k] / ETA[k] for k in ETA) + AUX_BUS_W
    mains = dc_bus / FRONT_END_ETA
    return watts, total, CEILING-total, mains, mains-total, all(checks) and total <= CEILING


def main():
    print("# Calculated arithmetic snapshot\n")
    print("Illustrative assumptions only; generated by `analysis/power_budget.py`.\n")
    print("| Scenario | Heater W | Anode W | Screen W | Grid reserve W | Sum W | Headroom W | Input W* | Internal overhead W* | Arithmetic fit |")
    print("|---|---:|---:|---:|---:|---:|---:|---:|---:|---|")
    for name, h, a, s, g in SCENARIOS:
        watts, total, headroom, mains, heat, ok = assess(h, a, s, g)
        values = [*watts.values(), total, headroom, mains, heat]
        print("| " + name + " | " + " | ".join(f"{v:.2f}" for v in values)
              + " | " + ("Yes; unvalidated" if ok else "No") + " |")
    print("\n*Two-stage model: rail efficiencies H/A/S/G = 85/80/75/70%; front end 90%; 12 W bus auxiliaries. Overhead = mains input minus delivered output. Rejected requests are not operating points. No duty/rating or grid-quadrant validation.\n")
    print("| Heater V | Current ceiling A | Power W |")
    print("|---:|---:|---:|")
    for v in map(D, ["1", "5", "6.3", "7.5", "12.6", "25", "50"]):
        i = min(D("8"), D("60") / v)
        print(f"| {v} | {i:.6f} | {v*i:.2f} |")
    # Boundary and infeasible-case checks substantiate the reconciliation.
    assert not assess(("7.5", "8"), ("600", ".15"), ("300", ".05"), "0")[-1]
    assert assess(("7.5", "8"), ("300", ".15"), ("280", ".05"), "1")[-1]
    assert not assess(("7.5", "8.01"), ("0", "0"), ("0", "0"), "0")[-1]
    assert not assess(("0", "0"), ("600", ".2"), ("0", "0"), "0")[-1]
    assert not assess(("0", "0"), ("0", "0"), ("500", ".05"), "0")[-1]
    assert D("90") / D(".2") == 450
    assert D("15") / D("500") == D(".03")
    assert D("60") / D("8") == D("7.5")
    print("\nBoundary and deliberately infeasible-case arithmetic checks passed.")


if __name__ == "__main__":
    main()
